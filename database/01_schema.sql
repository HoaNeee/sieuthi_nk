-- Run manually as SIEUTHI in FREEPDB1, on a NEW schema only.
-- No DROP, no automatic startup execution. Oracle sequences are not gapless.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
BEGIN
  IF USER <> 'SIEUTHI' OR SYS_CONTEXT('USERENV','CON_NAME') <> 'FREEPDB1' THEN
    RAISE_APPLICATION_ERROR(-20001, 'Connect as SIEUTHI in FREEPDB1');
  END IF;
END;
/
CREATE TABLE DANH_MUC (MA_DM NUMBER(19) PRIMARY KEY, TEN_DM VARCHAR2(150 CHAR) NOT NULL, MO_TA VARCHAR2(500 CHAR));
CREATE TABLE NHA_CUNG_CAP (MA_NCC NUMBER(19) PRIMARY KEY, TEN_NCC VARCHAR2(150 CHAR) NOT NULL, SDT VARCHAR2(20 CHAR), DIA_CHI VARCHAR2(300 CHAR), EMAIL VARCHAR2(150 CHAR));
CREATE TABLE NHAN_VIEN (
 MA_NV NUMBER(19) PRIMARY KEY, HO_TEN VARCHAR2(150 CHAR) NOT NULL, CHUC_VU VARCHAR2(100 CHAR),
 TEN_DANG_NHAP VARCHAR2(80 CHAR) NOT NULL UNIQUE, MAT_KHAU VARCHAR2(255 CHAR) NOT NULL,
 VAI_TRO VARCHAR2(10 CHAR) NOT NULL CHECK (VAI_TRO IN ('ADMIN','STAFF')),
 TRANG_THAI VARCHAR2(8 CHAR) DEFAULT 'ACTIVE' NOT NULL CHECK (TRANG_THAI IN ('ACTIVE','INACTIVE'))
);
CREATE TABLE KHACH_HANG (
 MA_KH NUMBER(19) PRIMARY KEY, HO_TEN VARCHAR2(150 CHAR) NOT NULL, SDT VARCHAR2(20 CHAR),
 DIEM_TICH_LUY NUMBER(9) DEFAULT 0 NOT NULL CHECK (DIEM_TICH_LUY >= 0)
);
CREATE TABLE SAN_PHAM (
 MA_SP NUMBER(19) PRIMARY KEY, BARCODE VARCHAR2(80 CHAR) UNIQUE, TEN_SP VARCHAR2(150 CHAR) NOT NULL,
 GIA_BAN NUMBER(15,2) NOT NULL CHECK (GIA_BAN >= 0),
 SO_LUONG_TON NUMBER(9) DEFAULT 0 NOT NULL CHECK (SO_LUONG_TON >= 0), HAN_SU_DUNG DATE,
 MA_DM NUMBER(19) NOT NULL REFERENCES DANH_MUC(MA_DM),
 MA_NCC NUMBER(19) NOT NULL REFERENCES NHA_CUNG_CAP(MA_NCC)
);
CREATE TABLE PHIEU_NHAP (
 MA_PN NUMBER(19) PRIMARY KEY, NGAY_NHAP TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
 MA_NCC NUMBER(19) NOT NULL REFERENCES NHA_CUNG_CAP(MA_NCC),
 MA_NV NUMBER(19) NOT NULL REFERENCES NHAN_VIEN(MA_NV)
);
CREATE TABLE CT_PHIEU_NHAP (
 MA_CTPN NUMBER(19) PRIMARY KEY, SO_LUONG NUMBER(9) NOT NULL CHECK (SO_LUONG > 0),
 DON_GIA_NHAP NUMBER(15,2) NOT NULL CHECK (DON_GIA_NHAP >= 0),
 MA_PN NUMBER(19) NOT NULL REFERENCES PHIEU_NHAP(MA_PN),
 MA_SP NUMBER(19) NOT NULL REFERENCES SAN_PHAM(MA_SP)
);
CREATE TABLE HOA_DON (
 MA_HD NUMBER(19) PRIMARY KEY, NGAY_LAP TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
 HINH_THUC_TT VARCHAR2(20 CHAR) NOT NULL CHECK (HINH_THUC_TT IN ('TIEN_MAT','CHUYEN_KHOAN')),
 TONG_TIEN NUMBER(18,2) NOT NULL CHECK (TONG_TIEN >= 0),
 MA_NV NUMBER(19) NOT NULL REFERENCES NHAN_VIEN(MA_NV),
 MA_KH NUMBER(19) REFERENCES KHACH_HANG(MA_KH)
);
CREATE TABLE CT_HOA_DON (
 MA_CT NUMBER(19) PRIMARY KEY, SO_LUONG NUMBER(9) NOT NULL CHECK (SO_LUONG > 0),
 DON_GIA NUMBER(15,2) NOT NULL CHECK (DON_GIA >= 0),
 MA_HD NUMBER(19) NOT NULL REFERENCES HOA_DON(MA_HD),
 MA_SP NUMBER(19) NOT NULL REFERENCES SAN_PHAM(MA_SP)
);
CREATE SEQUENCE SEQ_DM START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE SEQ_NCC START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE SEQ_NV START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE SEQ_KH START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE SEQ_SP START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE SEQ_PN START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE SEQ_CTPN START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE SEQ_HD START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE SEQ_CT START WITH 1 INCREMENT BY 1 NOCYCLE;

